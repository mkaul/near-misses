#!/usr/bin/env python3
"""Regenerate maps-embedded.js (fallback so the editor works from file://).
Run after changing anything in maps/ (including faelle.json):  python3 embed-maps.py"""
import json, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
index = json.load(open("maps/index.json", encoding="utf8"))
files = {m["file"]: json.load(open(m["file"], encoding="utf8")) for m in index}
embedded = {"index": index, "files": files}
if os.path.exists("maps/faelle.json"):
    embedded["cases"] = json.load(open("maps/faelle.json", encoding="utf8"))
out = "/* generated by embed-maps.py - do not edit */\nwindow.__MAPS=" + json.dumps(embedded, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/") + ";\n"
open("maps-embedded.js", "w", encoding="utf8").write(out)
print("maps-embedded.js:", len(out), "bytes,", len(files), "maps,", len(embedded.get("cases", {}).get("cases", [])), "cases")
